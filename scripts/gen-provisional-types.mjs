// Generates provisional Supabase-style types from supabase/migrations/*.sql (ADR-009).
// Used only until the Supabase project is linked; then `npm run db:types` replaces it.
// Usage: node scripts/gen-provisional-types.mjs > lib/db/types.ts
import fs from "node:fs";
import path from "node:path";

const dir = "supabase/migrations";
const sql = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => fs.readFileSync(path.join(dir, f), "utf8"))
  .join("\n")
  .replace(/--[^\n]*/g, "");

const enums = {};
for (const m of sql.matchAll(/create type (\w+) as enum \(([^)]*)\)/g)) {
  enums[m[1]] = [...m[2].matchAll(/'([^']*)'/g)].map((x) => x[1]);
}

function splitTop(body) {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (const ch of body) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur.trim());
      cur = "";
      continue;
    }
    cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

function tsType(t) {
  const base = t.replace(/\(.*\)/, "").toLowerCase();
  const arr = base.endsWith("[]");
  const b = base.replace("[]", "");
  let r;
  if (enums[b]) r = `Database["public"]["Enums"]["${b}"]`;
  else if (["uuid", "text", "timestamptz", "vector", "date"].includes(b)) r = "string";
  else if (["int", "integer", "bigint", "numeric", "float"].includes(b)) r = "number";
  else if (b === "boolean") r = "boolean";
  else if (b === "jsonb") r = "Json";
  else throw new Error(`unknown type ${t}`);
  return arr ? `${r}[]` : r;
}

function column(def) {
  const [name, type] = def.split(/\s+/);
  const notNull = /not null|primary key/i.test(def);
  const optional = /\bdefault\b|generated/i.test(def) || !notNull;
  return { name, type: tsType(type), notNull, optional };
}

const tables = new Map();
const createRe = /create table public\.(\w+) \(/g;
let m;
while ((m = createRe.exec(sql))) {
  let i = createRe.lastIndex;
  let depth = 1;
  while (depth) {
    if (sql[i] === "(") depth++;
    if (sql[i] === ")") depth--;
    i++;
  }
  const body = sql.slice(createRe.lastIndex, i - 1);
  const cols = splitTop(body)
    .filter((p) => !/^(primary key|unique|check|constraint)\b/i.test(p))
    .map(column);
  tables.set(m[1], cols);
}

for (const alter of sql.matchAll(/alter table public\.(\w+)\s+(add column[\s\S]*?);/g)) {
  const cols = tables.get(alter[1]);
  if (!cols) continue;
  for (const part of splitTop(alter[2])) {
    const def = part.replace(/^add column (if not exists )?/i, "");
    const col = column(def);
    if (!cols.some((c) => c.name === col.name)) cols.push(col);
  }
}

const ind = (n) => " ".repeat(n);
let out = `// PROVISIONAL — generated by scripts/gen-provisional-types.mjs from supabase/migrations
// because the Supabase project is not linked yet (ADR-009). Replace with \`npm run db:types\`.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [name, cols] of tables) {
  const row = cols
    .map((c) => `${ind(10)}${c.name}: ${c.type}${c.notNull ? "" : " | null"};`)
    .join("\n");
  const ins = cols
    .map(
      (c) => `${ind(10)}${c.name}${c.optional ? "?" : ""}: ${c.type}${c.notNull ? "" : " | null"};`,
    )
    .join("\n");
  const upd = cols
    .map((c) => `${ind(10)}${c.name}?: ${c.type}${c.notNull ? "" : " | null"};`)
    .join("\n");
  out += `${ind(6)}${name}: {\n${ind(8)}Row: {\n${row}\n${ind(8)}};\n${ind(8)}Insert: {\n${ins}\n${ind(8)}};\n${ind(8)}Update: {\n${upd}\n${ind(8)}};\n${ind(8)}Relationships: [];\n${ind(6)}};\n`;
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
      has_role: { Args: { r: Database["public"]["Enums"]["user_role"] }; Returns: boolean };
      is_admin: { Args: Record<PropertyKey, never>; Returns: boolean };
      is_enrolled: { Args: { c: string }; Returns: boolean };
      fulfil_order: {
        Args: {
          p_order: string;
          p_provider_ref?: string;
          p_amount_minor?: number;
          p_currency?: string;
          p_verified_by?: string;
        };
        Returns: string;
      };
      is_course_staff: { Args: { c: string }; Returns: boolean };
      is_batch_member: { Args: { b: string }; Returns: boolean };
      lesson_course: { Args: { l: string }; Returns: string };
      match_kb: {
        Args: { query_embedding: string; match_count?: number };
        Returns: { id: string; content: string; similarity: number }[];
      };
      verify_certificate: {
        Args: { p_code: string };
        Returns: {
          name_on_cert: string;
          course_title: string;
          issued_at: string;
          status: Database["public"]["Enums"]["cert_status"];
        }[];
      };
    };
    Enums: {
`;
for (const [k, v] of Object.entries(enums))
  out += `${ind(6)}${k}: ${v.map((x) => `"${x}"`).join(" | ")};\n`;
out += `    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;
process.stdout.write(out);
